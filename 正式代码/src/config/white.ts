import type { Ratio } from './ratios';

// 白底图做法①：生图模型按原图出白底（技术写法第 7 节）。做法②（保留原像素的抠图）服务待发起人再定，暂未接入。
// 生图会重画像素，初测常常没有完整入框，所以提示词把「完整入框、不改结构」写在最前面。
export const WHITE = {
  ratio: '1:1' as Ratio,
  perAsset: 3, // 每张原图最多生成几次白底（含失败），防止反复花钱
  prompt: (keep: string) =>
    [
      '把参考图里的这件手作饰品放到纯白背景上，做成电商白底商品图。',
      '严格按参考图还原颜色、数量、轮廓、连接结构、纹样和材质，不添加扣头，不延长链条，不补出参考图里看不到的部分，闭合的环保持闭合。',
      keep ? `特别注意不能改：${keep}。` : '',
      '整件饰品完整入框，居中，四周留出足够边距，不被裁切。',
      '背景纯白（#ffffff），只有柔和的自然投影，没有道具、文字、水印或边框。',
    ]
      .filter(Boolean)
      .join(''),
};
